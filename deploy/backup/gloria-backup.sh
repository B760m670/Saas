#!/bin/sh
# Резервная копия баз: панели и бота.
#
# Запускается на сервере с панелью, по расписанию. Кладёт по файлу на базу,
# проверяет каждый и удаляет старые.
#
# Копия на той же машине спасает от неудачной миграции, ошибочного запроса и
# порчи данных. От потери самой машины она не спасает — для этого файлы надо
# уносить наружу, см. конец файла.

set -eu

# --- настройки ---------------------------------------------------------------

CONTAINER="${GLORIA_DB_CONTAINER:-remnawave-db}"
DEST="${GLORIA_BACKUP_DIR:-/var/backups/gloria}"
KEEP_DAYS="${GLORIA_BACKUP_KEEP_DAYS:-14}"

# Базы, которые надо снять. Панельная называется по-разному в разных
# сборках — уточните по `docker exec CONTAINER psql -U postgres -l`.
DATABASES="${GLORIA_BACKUP_DATABASES:-postgres gloria}"

# --- проверки до работы ------------------------------------------------------

if ! docker inspect "$CONTAINER" >/dev/null 2>&1; then
    echo "нет контейнера $CONTAINER" >&2
    exit 1
fi

mkdir -p "$DEST"
chmod 700 "$DEST"

STAMP=$(date -u +%Y%m%d-%H%M%S)
FAILED=0

# --- снятие ------------------------------------------------------------------

for db in $DATABASES; do
    file="$DEST/$db-$STAMP.sql.gz"

    # Пишем во временный файл: прерванный дамп не должен выглядеть готовым.
    # Именно такая копия обнаруживается в момент, когда она нужна.
    if docker exec "$CONTAINER" pg_dump -U postgres --no-owner "$db" 2>/dev/null \
        | gzip -9 > "$file.part"
    then
        # Целостность архива и непустота — две разные проверки, и обе нужны:
        # pg_dump молча отдаёт пустоту, когда базы нет.
        if gzip -t "$file.part" 2>/dev/null && [ "$(stat -c %s "$file.part")" -gt 1024 ]; then
            mv "$file.part" "$file"
            chmod 600 "$file"
            echo "снято: $file ($(stat -c %s "$file") байт)"
        else
            echo "дамп $db не прошёл проверку, отброшен" >&2
            rm -f "$file.part"
            FAILED=1
        fi
    else
        echo "не удалось снять $db" >&2
        rm -f "$file.part"
        FAILED=1
    fi
done

# --- уборка ------------------------------------------------------------------

# Старое удаляется только если сегодняшнее снялось. Иначе неделя неудачных
# запусков тихо съела бы все копии, и последнюю удалили бы ровно в тот день,
# когда она понадобилась.
if [ "$FAILED" -eq 0 ]; then
    find "$DEST" -name '*.sql.gz' -type f -mtime "+$KEEP_DAYS" -delete
else
    echo "были ошибки — старые копии оставлены" >&2
fi

exit "$FAILED"

# --- вынести наружу ----------------------------------------------------------
#
# Копия рядом с базой не переживёт потерю машины. Варианты, по возрастанию
# надёжности:
#
#   1. Забирать себе на компьютер (ничего не надо настраивать на серверах):
#        scp root@ПАНЕЛЬ:/var/backups/gloria/'*.sql.gz' ~/backup/
#
#   2. Складывать на второй сервер. Дёшево, но данные покупателей окажутся
#      на узле, который стоит под ударом первым, — взвесьте.
#
#   3. Хранилище у стороннего поставщика. Надёжнее всего и дороже всего по
#      последствиям утечки: дамп содержит все идентификаторы покупателей.
#      Только в зашифрованном виде.
