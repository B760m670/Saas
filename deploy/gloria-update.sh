#!/bin/sh
# Обновление бота и мини-приложения.
#
# Порядок важен: сборка идёт до остановки службы, чтобы простой был не
# минутами компиляции, а секундами копирования. И собранное ставится
# отдельно от исходников — иначе пересборка попыталась бы переписать файл
# работающего процесса и упёрлась бы в «Text file busy».
set -eu

BRANCH=${BRANCH:-claude/multiplatform-vpn-service-ur6ef4}
SRC=${SRC:-/opt/gloria-src}
SITE=${SITE:-/var/www/gloria}

# Витрина стоит отдельно от кабинета: у неё свой домен без «panel.» в имени,
# и одна папка на двоих означала бы, что личный кабинет открывается по
# публичному адресу, а витрина — по адресу панели.
SITE_PUBLIC=${SITE_PUBLIC:-/var/www/gloria-public}

# Реквизиты, которые публикуются в документах, но не хранятся в репозитории.
# Файл лежит только на сервере и содержит одну строку:
#
#     GLORIA_INN=000000000000
#
# ИНН попадёт на публичную страницу, но история git — другое дело: оттуда
# он уже не исчезнет, а репозиторий может стать открытым.
LEGAL=${LEGAL:-/etc/gloria-legal.env}

cd "$SRC"

echo "== обновляемся"
git fetch origin "$BRANCH"
git checkout -q FETCH_HEAD

# Перезапуск самого себя — обновившимся.
#
# `git checkout` только что подменил и этот файл, но продолжает выполняться
# **прежний**: интерпретатор читает скрипт по мере работы и держит открытым
# старый файл, а git подставляет новый отдельной записью. Изменения в самой
# выкладке поэтому вступали в силу лишь со следующего запуска.
#
# Это не мелочь. Дважды подряд выкладка падала на одной и той же миграции
# уже после того, как причина была исправлена и выложена: на диск правка
# приезжала, а работал по-прежнему старый код. Ошибка выглядела как «не
# помогло», хотя помогло.
#
# Повторяем один раз: флаг в окружении переживает exec и не даёт кругу
# замкнуться, если что-то пойдёт не так.
if [ -z "${GLORIA_UPDATE_RESTARTED:-}" ] && [ -r "$SRC/deploy/gloria-update.sh" ]; then
    GLORIA_UPDATE_RESTARTED=1
    export GLORIA_UPDATE_RESTARTED
    exec sh "$SRC/deploy/gloria-update.sh"
fi

echo "== схема базы"

# Как попасть в базу. Переменной, а не жёстко: так этот же блок проверяется
# на обычном PostgreSQL, без докера и без сервера.
DB_EXEC=${DB_EXEC:-"docker exec -i remnawave-db psql -U gloria -d gloria"}

# shellcheck disable=SC2086
db() { $DB_EXEC -v ON_ERROR_STOP=1 "$@"; }

# Учёт применённого.
#
# Раньше его не было, и единственным признаком «уже применена» служил отказ:
# упёрлась в «уже существует» — значит применена. Но отказы неразличимы,
# а вывод к тому же подавлялся, и под то же самое «пропущена (скорее всего,
# уже применена)» попадали опечатка в SQL, нехватка прав и недоступная база.
#
# Так и вышло: 0004 не применялась **ни разу**, каждая выкладка бодро
# сообщала «пропущена», а напоминания об окончании подписки молча падали на
# ограничении CHECK. Обнаружилось это случайно и спустя недели.
#
# Сама таблица учёта создаётся раньше всего: без неё нечем отличить
# применённое от неприменённого, а гадать мы больше не гадаем.
db -qtA >/dev/null <<'SQL'
SET client_min_messages = warning;
CREATE TABLE IF NOT EXISTS schema_migrations (
    name TEXT PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
SQL

# Заднее число: на базе, где схема стоит с тех времён, когда учёта не было,
# применённое опознаётся по следу в схеме.
#
# Сначала здесь стояло опознание по виду отказа — «упёрлась в объект, который
# уже есть, значит применена». На сервере это сломалось с первого же запуска:
# 0003 упала не с «уже есть», а с нарушением CHECK. База оказалась **новее**
# миграции (в ней уже стояла 0004, переименовывающая виды напоминаний ещё
# раз), и повторное применение 0003 возвращало набор значений, которого в
# строках больше нет.
#
# Отказ вообще ничего не говорит о применённости: он говорит лишь о том, что
# применить сейчас нельзя. Признак один — след в схеме.
db -qtA >/dev/null < db/backfill_migrations.sql

applied=$(db -qtAc 'SELECT name FROM schema_migrations')

for m in db/migrations/*.sql; do
    name=$(basename "$m")

    if printf '%s\n' "$applied" | grep -qxF "$name"; then
        echo "   уже применена $name"
        continue
    fi

    # VERBOSITY=verbose добавляет к ошибке её код — он пригодится в разборе,
    # а текст ошибки зависит от языка сервера и от версии.
    if out=$(db -v VERBOSITY=verbose < "$m" 2>&1); then
        echo "   применена $name"
    else
        # Настоящий отказ. Молчать здесь нельзя: бот поедет на схеме, которой
        # не хватает того, на что он рассчитывает, и узнается это по
        # неработающей мелочи спустя недели.
        echo "== схема не обновилась, на $name:" >&2
        printf '%s\n' "$out" >&2
        exit 1
    fi

    # Через ввод, а не через -c: переменные psql разворачивает только в том,
    # что прочитал сам. С -c имя ушло бы в запрос буквально, как `:'name'`,
    # и учёт не пополнялся бы вовсе.
    db -v name="$name" -qtA >/dev/null <<'SQL'
INSERT INTO schema_migrations (name) VALUES (:'name')
ON CONFLICT (name) DO NOTHING;
SQL
done

echo "== сборка"

# cargo ставится rustup в домашний каталог и в системный PATH не попадает.
# Через sudo PATH вдобавок подменяется на secure_path из sudoers — и
# «cargo: not found» вылезает даже у root, у которого он есть. Ищем сами,
# чтобы скрипт не зависел от того, как его запустили.
if ! command -v cargo >/dev/null 2>&1; then
    for dir in "${HOME:-/root}/.cargo/bin" /root/.cargo/bin /usr/local/cargo/bin; do
        if [ -x "$dir/cargo" ]; then
            PATH="$dir:$PATH"
            export PATH
            break
        fi
    done
fi

if ! command -v cargo >/dev/null 2>&1; then
    echo "не найден cargo; если он не установлен:" >&2
    echo "  curl --proto '=https' --tlsv1.2 -sSf https://sh.rustup.rs | sh" >&2
    exit 1
fi

( cd bot && cargo build --release )

echo "== мини-приложение"
install -m 644 site/index.html "$SITE/index.html"

# Документы выкладываются вместе со страницей: ссылки на них строятся от её
# адреса, и забытая копия оставила бы в кабинете три пункта в никуда. На них
# же ссылается платёжный сервис, а для него неработающая оферта — повод
# отключить приём оплаты.
#
# Имени владельца в документах нет по его решению; ИНН подставляется здесь,
# из файла на сервере.
if [ ! -r "$LEGAL" ]; then
    echo "нет файла $LEGAL — в документах остался бы {{ИНН}} вместо номера" >&2
    exit 1
fi
. "$LEGAL"

if [ -z "${GLORIA_INN:-}" ]; then
    echo "в $LEGAL не задан GLORIA_INN" >&2
    exit 1
fi

# Подстановка при выкладке, а не при сборке: файлы в репозитории остаются
# без реквизитов, и следующий git pull ничего не затирает.
publish_legal() {
    sed "s/{{ИНН}}/$GLORIA_INN/g" "$1" > "$2.tmp"
    if grep -q '{{' "$2.tmp"; then
        echo "в $1 остались неподставленные значения" >&2
        rm -f "$2.tmp"
        exit 1
    fi
    install -m 644 "$2.tmp" "$2"
    rm -f "$2.tmp"
}

install -d -m 755 "$SITE/legal"
for f in site/legal/*.html; do
    publish_legal "$f" "$SITE/legal/$(basename "$f")"
done
install -m 644 site/legal/legal.css "$SITE/legal/legal.css"

# Витрина: то, что видит человек, открывший адрес в обычном браузере, и то,
# что смотрит модератор платёжного сервиса. Без неё по адресу открывается
# личный кабинет, рассчитанный на Telegram, — без подписи он показывает
# прочерки и выглядит как недоделанный сайт.
install -d -m 755 "$SITE_PUBLIC"
publish_legal site/landing/index.html "$SITE_PUBLIC/index.html"

echo "== бот"
systemctl stop gloria-bot
install -m 755 bot/target/release/gloria /opt/gloria/gloria
systemctl start gloria-bot

sleep 2
systemctl is-active --quiet gloria-bot && echo "== готово" || {
    echo "== бот не поднялся:"
    journalctl -u gloria-bot -n 20 --no-pager
    exit 1
}
