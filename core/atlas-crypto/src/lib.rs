//! Криптографический фундамент ATLAS.
//!
//! Собственных криптографических алгоритмов здесь нет и не будет. Крейт
//! собирает аудированные примитивы в те конструкции, которые нужны проекту,
//! и задаёт единые правила их применения: один источник случайности, одна
//! хэш-функция, обязательное разделение по контексту, гибрид классики
//! и постквантовых схем везде, где это имеет смысл.
//!
//! # Состав
//!
//! - [`rng`] — единственный источник случайности;
//! - [`hash`] — BLAKE3: хэш, KDF, hex;
//! - [`sign`] — гибридные подписи Ed25519 + ML-DSA-65;
//! - [`kem`] — гибридный обмен ключами X25519 + ML-KEM-768;
//! - [`credentials`] — генерация учётных данных для своих точек выхода.
//!
//! # Почему гибрид
//!
//! Классические схемы (Ed25519, X25519) падут перед достаточно большим
//! квантовым компьютером, а трафик пишется уже сегодня в расчёте на
//! расшифровку потом. Постквантовые схемы (ML-DSA, ML-KEM) молоды, и у них
//! может обнаружиться классическая слабость. Комбинация требует сломать оба
//! независимых допущения сразу.
#![forbid(unsafe_code)]
#![warn(missing_docs, clippy::pedantic)]

pub mod credentials;
mod error;
pub mod hash;
pub mod kem;
pub mod rng;
pub mod sign;

pub use error::{Error, Result};
