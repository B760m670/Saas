//! Ошибки разбора и построения `ClientHello`.

/// Результат операции над сообщением TLS.
pub type Result<T> = core::result::Result<T, Error>;

/// Ошибка разбора или построения.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum Error {
    /// Ввод закончился раньше, чем требовала объявленная длина.
    #[error("сообщение обрывается на середине")]
    Truncated,

    /// Структура нарушена: несогласованные длины, недопустимые значения.
    #[error("некорректная структура: {0}")]
    Malformed(&'static str),

    /// Не тот тип сообщения — например, `ServerHello` вместо `ClientHello`.
    #[error("ожидался ClientHello, получен тип {0:#04x}")]
    UnexpectedMessage(u8),

    /// Значение не помещается в поле объявленной ширины.
    #[error("значение не помещается в поле длины")]
    TooLong,

    /// Проверка подлинности записи не прошла.
    ///
    /// Причина намеренно не уточняется: подробность здесь — оракул
    /// для атакующего.
    #[error("проверка подлинности не прошла")]
    Aead,

    /// Собеседник нарушил порядок или содержание рукопожатия.
    #[error("нарушение протокола: {0}")]
    Protocol(&'static str),

    /// Собеседник предложил то, чего мы не умеем.
    #[error("не поддерживается: {0}")]
    Unsupported(&'static str),

    /// Сервер прислал предупреждение с указанным кодом.
    ///
    /// Коды описаны в RFC 8446, раздел 6. Самые частые: `40`
    /// (`handshake_failure`), `47` (`illegal_parameter`), `112`
    /// (`unrecognized_name`), `116` (`certificate_required`).
    #[error("сервер прислал alert {0}")]
    Alert(u8),

    /// Проверка подлинности сервера не прошла.
    #[error("сервер не прошёл проверку подлинности: {0}")]
    Untrusted(&'static str),

    /// Соединение закрыто и больше не может использоваться.
    #[error("соединение закрыто")]
    Closed,
}
