//! Приём оплаты подписки.
//!
//! Товар — не ключ, а ссылка на подписку, по которой клиент забирает ключи и
//! обновляет их, когда меняется адрес сервера. Продаётся доступ к этой
//! ссылке на срок. Всё, что здесь есть, обслуживает один вопрос: оплачен ли
//! срок и с какого момента его считать.
//!
//! # Почему провайдер вынесен за интерфейс
//!
//! Платёжные сервисы, доступные без юридического лица, живут месяцами.
//! Условия меняются, приём карт отваливается, сервис пропадает вместе с
//! балансом. Это не риск, который можно снизить выбором, — это свойство
//! всего яруса, и планировать надо на смену рельсы, а не на её постоянство.
//!
//! Поэтому о деньгах знает ровно один тип — [`PaymentEvent`]. Выдача
//! подписки, продление, отзыв ключа и рефералка висят на нём и не знают, кто
//! прислал деньги. Подключение нового сервиса — это новая реализация
//! [`Provider`] в отдельном файле; ничего существующего оно не задевает.
//!
//! # Почему здесь нет сети
//!
//! Крейт не содержит HTTP-клиента. Адаптер собирает запрос
//! ([`http::Request`]) и разбирает пришедшие байты, а выполняет обмен
//! вызывающий код. Это не архитектурная чистота ради чистоты: проверка
//! подписи уведомления — единственное, что отделяет сообщение сервиса от
//! подделки, и на живом сервисе её не проверить. Настоящее уведомление
//! требует настоящего платежа и показывает только то, что годная подпись
//! проходит; что негодная отвергается, живой платёж не покажет никогда.
//! Без ввода-вывода оба случая — обычный тест на готовых байтах.
//!
//! # Порядок подключения
//!
//! [`Manual`] работает сегодня и ничего не требует: бот показывает реквизиты,
//! владелец подтверждает платёж кнопкой. Сервис подключается потом и меняет
//! одну строку в настройке.

