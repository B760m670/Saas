//! Ошибки кодирования и разбора VLESS.

/// Результат операции над сообщением VLESS.
pub type Result<T> = core::result::Result<T, Error>;

/// Ошибка кодирования или разбора.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum Error {
    /// Данные закончились раньше, чем требовала структура.
    #[error("сообщение обрывается на середине")]
    Truncated,

    /// Версия протокола не поддерживается.
    #[error("неизвестная версия протокола: {0}")]
    UnsupportedVersion(u8),

    /// Неизвестный код команды.
    #[error("неизвестная команда: {0}")]
    UnknownCommand(u8),

    /// Неизвестный тип адреса.
    #[error("неизвестный тип адреса: {0}")]
    UnknownAddressType(u8),

    /// Доменное имя не является корректным UTF-8.
    #[error("доменное имя не в UTF-8")]
    InvalidDomain,

    /// Структура нарушена.
    #[error("некорректная структура: {0}")]
    Malformed(&'static str),

    /// Значение не помещается в поле своей ширины.
    #[error("значение не помещается в поле длины: {0}")]
    TooLong(&'static str),
}
