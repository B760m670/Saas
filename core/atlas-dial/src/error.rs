//! Ошибки сборки соединения.

/// Результат попытки соединения.
pub type Result<T> = core::result::Result<T, Error>;

/// Почему соединение не собралось.
#[derive(Debug, thiserror::Error)]
pub enum Error {
    /// Ключ описывает схему, которую мы пока не собираем.
    #[error("не поддерживается: {0}")]
    Unsupported(&'static str),

    /// В ключе не хватает поля либо оно некорректно.
    #[error("ключ доступа непригоден: {0}")]
    Key(&'static str),

    /// Отказ сети, рукопожатия или протокола.
    ///
    /// Ошибки TLS и VLESS приходят сюда же: снаружи разница между
    /// «сеть недоступна» и «сервер не тот» несущественна — решение
    /// в обоих случаях одно, пробовать другую точку.
    #[error("соединение не установлено: {0}")]
    Io(#[from] std::io::Error),
}
