//! Проверка данных, которые Telegram передаёт мини-приложению.
//!
//! Мини-приложение открывается внутри Telegram и получает от него строку
//! `initData` — кто пользователь, когда открыл, с какими правами. Эту строку
//! оно присылает нам вместе с каждым запросом.
//!
//! Строка приходит **от клиента**, то есть от кого угодно. Поверить ей на
//! слово — значит раздать чужие подписки всякому, кто подставит чужой номер:
//! номер там обычным текстом, менять его не требует никаких навыков.
//!
//! Telegram подписывает строку ключом бота. Проверка подписи — единственное,
//! что отделяет «это Иван» от «это кто-то, назвавшийся Иваном», и делать её
//! надо на каждом запросе, а не при первом входе.

#![forbid(unsafe_code)]

mod init_data;

pub use init_data::{verify, Error, Verified, DEFAULT_MAX_AGE};
