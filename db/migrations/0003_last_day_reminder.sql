-- ---------------------------------------------------------------------------
-- Напоминание в последний день вместо сообщения после окончания
--
-- Было `on_expiry` — оно уходило, когда подписка уже закончилась и VPN уже
-- перестал подключаться. Такое сообщение рассказывает человеку то, что он
-- и так только что заметил сам, и читается как «мы дали вам отключиться».
--
-- Стало `last_day` — уходит, пока подписка ещё действует. Разница
-- принципиальная: до окончания это возможность продлить без перерыва, после
-- — извещение о случившемся.
--
-- Имя вида меняется вместе со смыслом. Оставить прежнее было бы дешевле на
-- одну миграцию и дороже на все последующие чтения: `on_expiry`, уходящий
-- до окончания, — это описание, которое врёт.
-- ---------------------------------------------------------------------------

BEGIN;

-- Ограничение снимается до правки строк: иначе UPDATE упрётся в него сам.
ALTER TABLE reminders_sent DROP CONSTRAINT IF EXISTS reminders_sent_kind_check;

-- Уже отправленные — если такие есть — считаем отправленными и в новом
-- виде. Иначе человек, получивший «подписка закончилась», получил бы
-- следом ещё и «заканчивается сегодня» о том же сроке.
UPDATE reminders_sent SET kind = 'last_day' WHERE kind = 'on_expiry';

ALTER TABLE reminders_sent
    ADD CONSTRAINT reminders_sent_kind_check
    CHECK (kind IN ('before_3d', 'last_day', 'after_3d'));

COMMIT;
