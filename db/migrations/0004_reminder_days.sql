-- ---------------------------------------------------------------------------
-- Напоминания привязаны к суткам, а не к трёхдневью
--
-- Было: «за три дня» и «меньше суток». Второе выглядело так:
--
--     Подписка заканчивается 30.09.2026, меньше чем через сутки.
--
-- Дата и оговорка об оставшемся сроке в одной строке — масло масляное:
-- человек знает, какое сегодня число. Осталось одно из двух, и выбрано
-- то, которое не требует счёта в уме: «завтра» и «сегодня».
--
-- Отсюда и новые окна — сутки до окончания и последние часы, — и новые
-- имена видов. Имя обязано совпадать со словом в сообщении: `before_3d`
-- у напоминания «истекает завтра» — описание, которое врёт.
-- ---------------------------------------------------------------------------

BEGIN;

ALTER TABLE reminders_sent DROP CONSTRAINT IF EXISTS reminders_sent_kind_check;

-- Прежние отметки переносятся, а не выбрасываются: иначе человек, уже
-- получивший напоминание об этом сроке, получил бы его второй раз.
UPDATE reminders_sent SET kind = 'day_before' WHERE kind IN ('before_3d', 'on_expiry');
UPDATE reminders_sent SET kind = 'same_day'   WHERE kind = 'last_day';

ALTER TABLE reminders_sent
    ADD CONSTRAINT reminders_sent_kind_check
    CHECK (kind IN ('day_before', 'same_day', 'after_3d'));

COMMIT;
