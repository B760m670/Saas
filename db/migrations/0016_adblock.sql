-- ---------------------------------------------------------------------------
-- Опция «Без рекламы»
--
-- Тот же VPN, но реклама, трекеры и вредоносные сайты не открываются: их
-- адреса фильтрует свой DNS (AdGuard Home). Продаётся тарифами с опцией —
-- те же сроки, цена чуть выше. Проба включает опцию: проба показывает то,
-- что продаётся.
--
-- Опция — не отдельный тариф с отдельным сроком подписки, а дата
-- `users.adblock_until`: до неё у человека в панели есть ещё и отряд с
-- серверами без рекламы. Покупка с опцией ставит дату на новый конец
-- подписки; покупка без опции её не трогает — оплаченное с опцией не
-- пропадает, а после этой даты подписка продолжается уже без неё.
--
-- В `panel_plan` появляется `plus` — подписка с опцией.
-- ---------------------------------------------------------------------------

BEGIN;

ALTER TABLE users ADD COLUMN adblock_until TIMESTAMPTZ;

ALTER TABLE users DROP CONSTRAINT users_panel_plan_check;
ALTER TABLE users ADD CONSTRAINT users_panel_plan_check
    CHECK (panel_plan IN ('paid', 'free', 'personal', 'plus'));

COMMENT ON COLUMN users.panel_plan IS
    'Подтверждённое панелью: paid — прежний платный (3 устройства) или проба без опции, personal — тариф, plus — тариф или проба с опцией «Без рекламы», free — только бесплатный отряд. NULL — не отвозили.';

COMMIT;
