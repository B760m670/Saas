-- ---------------------------------------------------------------------------
-- Бесплатный доступ после окончания подписки
--
-- До этой миграции срок гасила панель: наступила дата — пользователь
-- `EXPIRED`, и с узлов он убран целиком. Вместе с платными серверами
-- пропадал и бесплатный путь в Telegram — тот самый, по которому человек
-- пришёл бы в бота продлевать.
--
-- Теперь, если задан `GLORIA_FREE_SQUADS`, гасит бот: по нашей дате он
-- переводит человека в бесплатные отряды, а в панели держит его живым.
-- Платные серверы перестают работать, бесплатный остаётся.
--
-- Колонка — то, что панель о человеке подтвердила: какие отряды у него
-- стоят. Расхождение с тем, что должно стоять по нашей дате, — работа для
-- очереди, ровно как расхождение дат в `0002_panel_sync.sql`.
-- ---------------------------------------------------------------------------

BEGIN;

-- NULL — отряды мы ещё не отвозили ни разу. У всех, кто заведён до этой
-- миграции, здесь NULL, и при включении бесплатного доступа очередь сама
-- отвезёт каждому его отряды: отдельного переноса данных не нужно.
ALTER TABLE users ADD COLUMN panel_plan TEXT
    CHECK (panel_plan IN ('paid', 'free'));

COMMENT ON COLUMN users.panel_plan IS
    'Отряды, подтверждённые панелью: paid — платные и бесплатные, free — только бесплатные. NULL — не отвозили.';

COMMIT;
