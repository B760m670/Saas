-- ---------------------------------------------------------------------------
-- Поддержка: одно обращение за раз
--
-- Обращение уходит владельцу и ждёт ответа. Пока ответа нет, писать снова
-- незачем: очередь от этого не движется, а у владельца вместо одного
-- обращения оказывается шесть — и он читает их шесть раз вместо одного.
--
-- Отметка ставится в момент отправки и снимается ответом владельца. Пока
-- она стоит, следующее сообщение до владельца не доходит: человеку
-- говорится, что обращение уже принято.
--
-- # Почему у отметки есть время, а не просто «да/нет»
--
-- Флаг «ждёт ответа» без времени запирает человека навсегда, если владелец
-- не ответил — заболел, проглядел, ответил голосом в другом месте. Хуже
-- всего это для того, у кого не работает оплаченный VPN: он не может даже
-- напомнить о себе.
--
-- Поэтому отметка хранит **когда**, а право написать возвращается само,
-- если ответа нет слишком долго. Молчание поддержки — не повод лишать
-- человека голоса.
-- ---------------------------------------------------------------------------

BEGIN;

-- Когда отправлено обращение, на которое ещё не ответили.
-- NULL — открытых обращений нет, писать можно.
ALTER TABLE users ADD COLUMN IF NOT EXISTS support_pending_at TIMESTAMPTZ;

COMMENT ON COLUMN users.support_pending_at IS
    'Время неотвеченного обращения. NULL — можно писать снова.';

COMMIT;
