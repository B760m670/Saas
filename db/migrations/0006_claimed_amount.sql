-- ---------------------------------------------------------------------------
-- Счёт помнит не только «оплатил», но и сколько
--
-- Отметки о нажатии (0005) не хватило. Она отвечает «этот человек говорит,
-- что перевёл», а вопрос у владельца другой: в выписке лежат 200 ₽ и 199 ₽,
-- и оба нажавших молчат о том, кто из них кто.
--
-- Уникальный хвост копеек их не различает — именно потому, что они его не
-- отправили. Круглую сумму человек выбирает сам, и знает о ней только он.
--
-- Поэтому теперь его об этом спрашивают, и ответ хранится здесь. Дальше
-- совпадение точное: 200 ₽ в выписке — это тот, кто сказал «200».
--
-- Сумма — **слова покупателя**, а не наш счёт и не подтверждение оплаты.
-- Проверяет её владелец по выписке, зачисляет своей командой. Ошибиться в
-- ней человек может так же, как ошибся с самим переводом.
-- ---------------------------------------------------------------------------

BEGIN;

ALTER TABLE orders ADD COLUMN IF NOT EXISTS claimed_minor BIGINT;

COMMENT ON COLUMN orders.claimed_minor IS
    'Сколько покупатель говорит, что отправил. Его слова, не подтверждение.';

-- Ноль и отрицательное — не «перевёл мало», а испорченное число.
ALTER TABLE orders DROP CONSTRAINT IF EXISTS claimed_amounts_are_positive;
ALTER TABLE orders
    ADD CONSTRAINT claimed_amounts_are_positive
    CHECK (claimed_minor IS NULL OR claimed_minor > 0);

-- Сумма без нажатия невозможна: она приходит вместе с ним.
--
-- Обратное — нажатие без суммы — разрешено намеренно: так выглядят отметки,
-- поставленные до этой миграции, когда сумму ещё не спрашивали. Запретить
-- их значило бы не пустить миграцию на работающей базе.
ALTER TABLE orders DROP CONSTRAINT IF EXISTS claimed_amounts_follow_a_claim;
ALTER TABLE orders
    ADD CONSTRAINT claimed_amounts_follow_a_claim
    CHECK (claimed_minor IS NULL OR claimed_at IS NOT NULL);

COMMIT;
