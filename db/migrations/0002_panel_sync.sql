-- ---------------------------------------------------------------------------
-- Очередь согласования даты с панелью
--
-- До этой миграции наша дата окончания никуда не уезжала: оплата продлевала
-- `users.expires_at`, а панель об этом не узнавала. Человек платил, и для него
-- не менялось ничего.
--
-- Гасить просроченных нам не нужно — это делает сама панель: у неё есть
-- события `user.expired`, `user.disabled`, `user.limited`, то есть статусы она
-- меняет своей рукой по той дате, которая у неё записана. Отсюда и вся наша
-- работа: чтобы её дата совпадала с нашей. Одна дата, а не два состояния.
--
-- Чинится не «вызовом панели после оплаты», а очередью. Вызов после оплаты
-- теряется при любом обрыве связи — ровно в тот момент, когда деньги уже
-- взяты. Очередь при обрыве просто остаётся непустой и разгребается на
-- следующем круге, сколько бы кругов ни понадобилось.
-- ---------------------------------------------------------------------------

BEGIN;

-- Дата, которую панель у себя подтвердила. NULL — не отправляли ни разу.
--
-- Ставится только после успешного ответа панели. Ставить её заранее значило
-- бы считать потерянный запрос выполненным, а расхождение — единственное, по
-- чему мы вообще узнаём о работе.
ALTER TABLE users ADD COLUMN panel_expires_at TIMESTAMPTZ;

COMMENT ON COLUMN users.panel_expires_at IS
    'Дата, подтверждённая панелью. Расхождение с expires_at — это работа в очереди.';

-- Очередь спрашивают на каждом круге цикла, а пуста она почти всегда. Без
-- указателя это полный просмотр таблицы несколько раз в минуту: сегодня
-- незаметно, на десяти тысячах покупателей заметно.
--
-- Указатель частичный, и в него попадают только несогласованные строки —
-- значит его размер зависит не от числа покупателей, а от числа тех, до кого
-- панель ещё не доехала. В норме это ноль.
CREATE INDEX users_awaiting_panel
    ON users (telegram_id)
    WHERE panel_id IS NOT NULL
      AND expires_at IS NOT NULL
      AND expires_at IS DISTINCT FROM panel_expires_at;

COMMIT;
