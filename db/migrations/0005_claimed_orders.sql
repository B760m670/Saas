-- ---------------------------------------------------------------------------
-- Счёт помнит, что покупатель сказал «я оплатил»
--
-- Уникальный хвост копеек отвечает на вопрос «чей платёж», пока человек
-- вводит сумму как названо: 198,63 назвали ровно одному, и пришедшие 198,63
-- принадлежат ему.
--
-- Он ломается, когда сумму вводят по памяти: круглые 199 или 200 не
-- принадлежат никому намеренно — иначе платёж по памяти зачислился бы
-- чужому заказу. Такой перевод уходит в ручной разбор, и разбирать его до
-- сих пор было нечем: открытых счетов много, и все они одинаково похожи на
-- правду.
--
-- Отметка сужает круг до тех, кто прямо сейчас говорит, что перевёл. Их
-- обычно один. Двое одновременно — уже редкость, а не обычный день, и
-- различить их можно по времени: банк показывает, когда пришли деньги.
--
-- Отметка не подтверждение и подтверждением стать не может: нажимает её
-- покупатель, а видит поступление только владелец счёта.
-- ---------------------------------------------------------------------------

BEGIN;

ALTER TABLE orders ADD COLUMN IF NOT EXISTS claimed_at TIMESTAMPTZ;

COMMENT ON COLUMN orders.claimed_at IS
    'Когда покупатель сказал, что перевёл. Не подтверждение оплаты.';

-- Сказать «оплатил» раньше, чем счёт выставлен, нельзя: такая отметка
-- означала бы перепутанные часы, а по ним потом сверяют выписку.
ALTER TABLE orders DROP CONSTRAINT IF EXISTS claims_follow_the_invoice;
ALTER TABLE orders
    ADD CONSTRAINT claims_follow_the_invoice
    CHECK (claimed_at IS NULL OR claimed_at >= created_at);

COMMIT;
