-- ---------------------------------------------------------------------------
-- Бонусы за приглашённых
--
-- Один бонус — один рубль скидки. Начисляются пригласившему, когда
-- приведённый им человек оплатил, и тратятся при следующей покупке.
--
-- # Журнал, а не счётчик
--
-- Баланс мог бы лежать одним числом в `users`, и это было бы короче на
-- целую таблицу. Но число не отвечает ни на один вопрос, который про
-- бонусы задают: откуда они взялись, куда делись, почему было двести, а
-- стало сто. Спор «у меня пропали бонусы» с одним числом разбирается
-- словом владельца против слова покупателя.
--
-- Здесь баланс — сумма журнала. Возврат — обратная запись, а не правка
-- прошлой: исправленная запись стирает след, а он и есть всё, ради чего
-- журнал заведён.
--
-- # Резерв при выставлении счёта
--
-- Бонусы списываются, когда счёт **выставлен**, а не когда оплачен. Иначе
-- человек с сорока бонусами открыл бы три счёта подряд и получил скидку
-- трижды на одни и те же сорок.
--
-- Неоплаченный счёт живёт сутки; когда он истекает, резерв возвращается
-- обратной записью.
-- ---------------------------------------------------------------------------

BEGIN;

CREATE TABLE bonus_ledger (
    id BIGSERIAL PRIMARY KEY,

    -- Чей бонус.
    telegram_id BIGINT NOT NULL REFERENCES users (telegram_id),

    -- Со знаком: начисление положительно, списание отрицательно. Ноль
    -- запрещён — запись, ничего не меняющая, только засоряет журнал.
    amount BIGINT NOT NULL CHECK (amount <> 0),

    -- Откуда запись:
    --   referral — начислено за оплату приведённого;
    --   reserve  — списано под выставленный счёт;
    --   refund   — возвращено с истёкшего счёта;
    --   manual   — правка руками, на случай разбора.
    reason TEXT NOT NULL CHECK (reason IN ('referral', 'reserve', 'refund', 'manual')),

    -- К какому заказу относится. Для `manual` пусто.
    order_id TEXT REFERENCES orders (id),

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Знак обязан соответствовать смыслу. Начисление со знаком минус —
    -- это не запись о начислении, а тихая кража.
    CONSTRAINT bonus_sign_matches_reason CHECK (
        (reason = 'referral' AND amount > 0) OR
        (reason = 'reserve'  AND amount < 0) OR
        (reason = 'refund'   AND amount > 0) OR
        (reason = 'manual')
    ),

    -- Всё, кроме ручной правки, привязано к заказу: без него непонятно,
    -- за что начислено и под что зарезервировано.
    CONSTRAINT bonus_knows_its_order CHECK (
        (reason = 'manual') OR (order_id IS NOT NULL)
    )
);

COMMENT ON TABLE bonus_ledger IS
    'Движение бонусов. Баланс — сумма записей, а не отдельное поле.';

-- Вторая линия от повторов.
--
-- Первая — порядок действий в `settle`: повторное подтверждение не доходит
-- до начисления, потому что раньше упирается в статус заказа. Эти индексы
-- ничего не ловят, пока тот порядок цел, и в том их смысл: они переживут
-- правку, при которой он изменится.
--
-- Начисление за один заказ друга — один раз, резерв и возврат по счёту —
-- тоже по разу.
CREATE UNIQUE INDEX bonus_referral_once ON bonus_ledger (order_id)
    WHERE reason = 'referral';
CREATE UNIQUE INDEX bonus_reserve_once ON bonus_ledger (order_id)
    WHERE reason = 'reserve';
CREATE UNIQUE INDEX bonus_refund_once ON bonus_ledger (order_id)
    WHERE reason = 'refund';

-- Баланс считается по человеку, и считается часто: при каждом открытии
-- кабинета и каждом выставлении счёта.
CREATE INDEX bonus_by_person ON bonus_ledger (telegram_id);

-- Сколько бонусов ушло в скидку по этому счёту.
--
-- Лежит в заказе, а не выводится из журнала, потому что нужно там же, где
-- сумма: счёт выставлен на 159 ₽ вместо 199 ₽ — и видно, почему.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS bonus_spent BIGINT NOT NULL DEFAULT 0
    CHECK (bonus_spent >= 0);

COMMENT ON COLUMN orders.bonus_spent IS
    'Сколько бонусов списано под этот счёт. Возвращаются, если он истёк.';

COMMIT;
