-- ---------------------------------------------------------------------------
-- Поддержка: кому какое сообщение переслано
--
-- Обращения идут через отдельного бота, и владелец отвечает на них свайпом.
-- Telegram при этом сообщает номер процитированного сообщения — но не того,
-- кто его прислал. Связь «наше сообщение владельцу → покупатель» больше
-- нигде не хранится, а без неё ответ адресовать нечем.
--
-- Другой способ — набирать номер человека в каждом ответе — работает, но
-- живёт на внимательности: один раз ошибиться цифрой, и ответ уходит
-- чужому вместе со всем, что в нём написано. Свайп ошибиться не даёт.
--
-- Строки живут недолго по смыслу, но не удаляются: переписка о деньгах
-- разбирается спустя недели, а места одна строка занимает столько же,
-- сколько номер.
-- ---------------------------------------------------------------------------

BEGIN;

CREATE TABLE support_messages (
    -- Куда переслано и каким номером. Пара, а не один номер: номера
    -- сообщений уникальны внутри чата, и у двух владельцев они совпадут.
    admin_chat_id BIGINT NOT NULL,
    admin_message_id BIGINT NOT NULL,

    -- Чьё обращение. Ссылка на пользователя намеренно: отвечать тому, кого
    -- у нас нет, незачем.
    telegram_id BIGINT NOT NULL REFERENCES users (telegram_id),

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    PRIMARY KEY (admin_chat_id, admin_message_id)
);

COMMENT ON TABLE support_messages IS
    'Пересланные обращения. По номеру сообщения находится, кому отвечать.';

-- Тема, которую человек выбрал последней.
--
-- Хранится у пользователя, а не отдельной таблицей: строка одна на человека
-- и всё время переписывается. Отдельная таблица здесь была бы таблицей
-- ровно с одной живой строкой на каждого.
--
-- Нужна затем, чтобы обращение доходило до владельца с подписью «о чём
-- речь». Человек, выбравший тему и написавший через полчаса, скорее всего
-- пишет о ней же; выбравший неделю назад — вряд ли, поэтому у отметки есть
-- время, и старая тема к сообщению не приписывается.
ALTER TABLE users ADD COLUMN IF NOT EXISTS support_topic TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS support_topic_at TIMESTAMPTZ;

-- Тема без времени — запись, по которой нельзя понять, свежая ли она.
ALTER TABLE users DROP CONSTRAINT IF EXISTS support_topic_knows_when;
ALTER TABLE users
    ADD CONSTRAINT support_topic_knows_when
    CHECK ((support_topic IS NULL) = (support_topic_at IS NULL));

COMMIT;
