//! Поддержка: темы обращений и готовые ответы.
//!
//! Отдельный бот, а не переписка с человеком. Личный аккаунт показывает
//! покупателю, кто за сервисом стоит, и не даёт ни очереди, ни порядка:
//! обращения теряются среди обычной переписки, а кто написал — видно только
//! по имени, которое человек мог и сменить.
//!
//! # Зачем здесь готовые ответы
//!
//! Поддержка — один человек, и он же чинит, выкладывает и подтверждает
//! оплаты. Половина обращений приходится на пять вопросов, ответы на
//! которые известны заранее. Бот, отвечающий на них сам, снимает эту
//! половину — и делает это мгновенно, а не «обычно в течение часа».
//!
//! Поэтому у каждой темы есть ответ, и написать человеку предлагается
//! **после** него, а не вместо. Тому, кому ответ не подошёл, мешает одно
//! лишнее нажатие; тому, кому подошёл, — сэкономлен час ожидания.
//!
//! Модуль чистый: ни базы, ни сети. Тексты проверяются тестами, а не
//! перепиской с живым ботом.

/// Тема обращения.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Topic {
    /// Заплатил, а подписка не продлилась.
    Payment,
    /// VPN не подключается.
    NoConnection,
    /// Работает, но медленно.
    Slow,
    /// Вопрос про деньги: возврат, ошибочный перевод.
    Money,
    /// Всё остальное.
    Other,
}

impl Topic {
    /// Все темы в том порядке, в каком они показываются.
    ///
    /// Порядок не случаен: первой стоит та, что дороже всего человеку.
    /// Заплативший и не получивший доступ ждать не должен.
    #[must_use]
    pub const fn all() -> [Self; 5] {
        [
            Self::Payment,
            Self::NoConnection,
            Self::Slow,
            Self::Money,
            Self::Other,
        ]
    }

    /// Короткое имя для кнопки.
    #[must_use]
    pub const fn code(self) -> &'static str {
        match self {
            Self::Payment => "pay",
            Self::NoConnection => "conn",
            Self::Slow => "slow",
            Self::Money => "money",
            Self::Other => "other",
        }
    }

    /// Разобрать имя, пришедшее с кнопки.
    #[must_use]
    pub fn parse(code: &str) -> Option<Self> {
        Self::all().into_iter().find(|topic| topic.code() == code)
    }

    /// Надпись на кнопке.
    #[must_use]
    pub const fn title(self) -> &'static str {
        match self {
            Self::Payment => "Оплатил, но подписка не продлилась",
            Self::NoConnection => "VPN не подключается",
            Self::Slow => "Работает медленно",
            Self::Money => "Вопрос по оплате или возврату",
            Self::Other => "Другое",
        }
    }

    /// Что бот отвечает сам.
    ///
    /// Ответы написаны так, чтобы человек мог проверить их у себя за минуту.
    /// «Обратитесь в поддержку» в конце нет намеренно: кнопка написать стоит
    /// под сообщением, и повторять её словами значит признать, что ответ
    /// ничего не решил.
    #[must_use]
    pub const fn answer(self) -> &'static str {
        match self {
            Self::Payment => {
                "Переводы приходят без имени отправителя — платёж я нахожу по сумме.\n\n\
                 Если счёт ещё открыт, вернитесь в него и нажмите «Я оплатил», \
                 выбрав отправленную сумму: тогда я найду перевод в выписке. \
                 Подписка включится, как только деньги будут видны в банке.\n\n\
                 Счёт закрылся или оплата была давно — напишите, продлю вручную."
            }
            Self::NoConnection => {
                "Сначала проверьте два самых частых случая.\n\n\
                 <b>Обновите подписку в приложении</b> — круговой стрелкой, \
                 затем выберите сервер заново. У большинства дело в старых \
                 настройках, оставшихся с прошлого раза.\n\n\
                 <b>Проверьте мобильный интернет.</b> Во время региональных \
                 ограничений не работает ни один VPN, включая наш: ограничение \
                 стоит в сети оператора. По Wi-Fi в это же время всё работает — \
                 если так, дело именно в этом, и обойти его нечем."
            }
            Self::Slow => {
                "Сначала попробуйте выбрать в приложении второй сервер — \
                 в подписке их несколько, и они разные.\n\n\
                 Если медленно на мобильном интернете, а по Wi-Fi быстро, \
                 то замедляет оператор, а не сервер.\n\n\
                 Не помогло — напишите, в какое время и на каком интернете \
                 медленно. Посмотрю нагрузку."
            }
            Self::Money => {
                "Возврат возможен, условия — в публичной оферте, она в \
                 «Настройках» кабинета.\n\n\
                 Напишите, что случилось: ошиблись суммой, оплатили дважды, \
                 хотите вернуть деньги. Разберёмся."
            }
            Self::Other => {
                "Напишите, что случилось, — своими словами.\n\n\
                 Если дело в подключении, помогает сразу указать устройство \
                 и приложение: с ними я отвечу за один заход, а не после \
                 трёх уточняющих вопросов."
            }
        }
    }
}

/// Разобрать `/w <номер> <текст>` — запасной способ ответить.
///
/// Возвращает, кому и что, или `None`, если разобрать нечего.
///
/// Функция вынесена сюда из исполнителя намеренно: от неё зависит,
/// **кому уйдёт ответ**, а ошибиться в таком разборе легко и незаметно.
/// Так и вышло: после отсечения `/w` оставался ведущий пробел, первым
/// куском выходила пустая строка, и номер не разбирался — при том, что
/// команда выглядела набранной верно.
#[must_use]
pub fn parse_reply(text: &str) -> Option<(i64, &str)> {
    let rest = text.strip_prefix("/w")?;

    // Имя бота после команды Telegram дописывает в группах сам
    // (`/w@GloriaVPNSupport_Bot`). Без пробела после команды это не она:
    // «/word» началом совпадает, командой не является.
    let rest = match rest.split_once(char::is_whitespace) {
        Some((head, tail)) if head.is_empty() || head.starts_with('@') => tail,
        _ => return None,
    };

    let mut parts = rest.trim().splitn(2, char::is_whitespace);
    let buyer: i64 = parts.next()?.parse().ok()?;
    let body = parts.next().unwrap_or("").trim();

    // Номер без текста — не ответ. Отправлять пустое сообщение незачем, а
    // молчать в ответ на команду нельзя: владелец решит, что оно ушло.
    if body.is_empty() || buyer <= 0 {
        return None;
    }

    Some((buyer, body))
}

#[cfg(test)]
mod tests {
    use super::{parse_reply, Topic};

    /// Имя темы уезжает в кнопку и возвращается оттуда. Не разобравшись,
    /// нажатие выглядит как молчащая кнопка.
    #[test]
    fn every_topic_survives_a_button() {
        for topic in Topic::all() {
            assert_eq!(Topic::parse(topic.code()), Some(topic));
        }
        assert_eq!(Topic::parse("нет-такой"), None);
        assert_eq!(Topic::parse(""), None);
    }

    /// Имена тем должны быть разными: совпади два — одна из кнопок вела бы
    /// не туда, и заметно это было бы только по чужому ответу.
    #[test]
    fn topic_codes_are_unique() {
        let mut codes: Vec<&str> = Topic::all().iter().map(|t| t.code()).collect();
        codes.sort_unstable();
        let before = codes.len();
        codes.dedup();
        assert_eq!(codes.len(), before, "имена тем повторяются: {codes:?}");
    }

    /// У каждой темы обязан быть ответ, иначе бот отвечает пустотой на
    /// нажатие — худший вид поломки, потому что выглядит как «не работает».
    #[test]
    fn every_topic_answers_something_useful() {
        for topic in Topic::all() {
            assert!(!topic.title().is_empty(), "тема без надписи");
            assert!(
                topic.answer().len() > 80,
                "ответ у {:?} слишком короткий, чтобы чем-то помочь",
                topic.code()
            );
        }
    }

    /// Надпись на кнопке уходит в Telegram, а он режет длинные.
    #[test]
    fn titles_fit_a_button() {
        for topic in Topic::all() {
            assert!(
                topic.title().chars().count() <= 40,
                "надпись {:?} не поместится",
                topic.title()
            );
        }
    }

    /// От этого разбора зависит, кому уйдёт ответ. Ошибка здесь отправляет
    /// написанное владельцем чужому человеку.
    #[test]
    fn a_reply_command_is_read_correctly() {
        assert_eq!(
            parse_reply("/w 123456789 проверил, продлил"),
            Some((123_456_789, "проверил, продлил"))
        );

        // Имя бота Telegram дописывает сам в группах.
        assert_eq!(
            parse_reply("/w@GloriaVPNSupport_Bot 42 готово"),
            Some((42, "готово"))
        );

        // Лишние пробелы человек ставит, и переспрашивать из-за них глупо.
        assert_eq!(parse_reply("/w   42   готово  "), Some((42, "готово")));

        // Текст из нескольких строк доходит целиком.
        assert_eq!(
            parse_reply("/w 42 первая\nвторая"),
            Some((42, "первая\nвторая"))
        );
    }

    /// А неполное и чужое — не разбирается. Молча угадать здесь значит
    /// отправить письмо не тому.
    #[test]
    fn an_incomplete_reply_command_is_refused() {
        for text in [
            "/w",
            "/w ",
            "/w 42",
            "/w 42   ",
            "/w текст без номера",
            "/w -42 текст",
            "/w 0 текст",
            "/word 42 текст",
            "просто текст",
            "",
        ] {
            assert_eq!(parse_reply(text), None, "принято: {text:?}");
        }
    }
}
