//! Клиент панели Remnawave.
//!
//! Панель — единственное место, где живут ключи. Бот сам их не делает: он
//! просит панель завести человека, продлить срок, выключить по истечении.
//! Значит панель — единственная точка отказа для продаж, но не для уже
//! выданных ключей: узел о панели не спрашивает и продолжает пропускать
//! трафик, пока она лежит. Это правильный порядок отказа, и ломать его не
//! надо (docs/14-bot.md §11).
//!
//! Как и адаптеры платёжных сервисов, крейт не ходит в сеть: собирает
//! запросы и разбирает ответы. Ошибку в разборе ответа так можно поймать
//! обычным тестом, а не подбором на живой панели.

#![forbid(unsafe_code)]

